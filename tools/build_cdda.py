#!/usr/bin/env python3
"""Build named Red Book CD-DA tracks and append them to a pcfx-cdlink cue.

The stock toolchain cdlink only writes the MODE1 program track.  This companion
follows doom-pcfx's CD-DA layout: every WAV becomes a separate raw 44.1 kHz,
signed-16 stereo track, and a C header maps names to track numbers.
"""
from __future__ import annotations

import argparse
import audioop
from pathlib import Path
import re
import wave

CD_RATE = 44100
CD_SECTOR_BYTES = 2352
MARKER = "# CD-DA tracks generated by tools/build_cdda.py"


def stem_macro(path: Path) -> str:
    return re.sub(r"[^A-Za-z0-9]", "_", path.stem).upper()


def convert_wav(source: Path, target: Path) -> None:
    if target.exists() and target.stat().st_mtime >= source.stat().st_mtime:
        return
    with wave.open(str(source), "rb") as wav:
        channels = wav.getnchannels()
        width = wav.getsampwidth()
        rate = wav.getframerate()
        if width != 2 or channels not in (1, 2):
            raise ValueError(f"{source}: need 16-bit mono or stereo PCM WAV")
        state = None
        written = 0
        temporary = target.with_suffix(target.suffix + ".tmp")
        with temporary.open("wb") as out:
            while True:
                block = wav.readframes(32768)
                if not block:
                    break
                converted, state = audioop.ratecv(
                    block, width, channels, rate, CD_RATE, state
                )
                if channels == 1:
                    converted = audioop.tostereo(converted, width, 1, 1)
                out.write(converted)
                written += len(converted)
            padding = (-written) % CD_SECTOR_BYTES
            if padding:
                out.write(b"\0" * padding)
        temporary.replace(target)


def write_header(header: Path, tracks: list[tuple[Path, int]]) -> None:
    lines = [
        "/* Generated from NEWMUSIC/ by tools/build_cdda.py. */",
        "#ifndef SMB_PCFX_CDDA_TRACKS_H",
        "#define SMB_PCFX_CDDA_TRACKS_H",
        "",
    ]
    lines.extend(f"#define CDDA_TRACK_{stem_macro(wav):<13} {number}" for wav, number in tracks)
    lines.extend(["", "#endif", ""])
    header.write_text("\n".join(lines), encoding="ascii")


def write_cue(cue: Path, output: str, tracks: list[tuple[Path, int]]) -> None:
    base = cue.read_text(encoding="ascii")
    if MARKER in base:
        base = base.split(MARKER, 1)[0].rstrip() + "\n"
    lines = [base.rstrip(), MARKER]
    for wav, number in tracks:
        lines.extend([
            f'FILE "{output}_{stem_macro(wav)}.bin" BINARY',
            f"  TRACK {number:02d} AUDIO",
            "    INDEX 01 00:00:00",
        ])
    cue.write_text("\n".join(lines) + "\n", encoding="ascii")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--music-dir", type=Path, required=True)
    parser.add_argument("--output", required=True)
    parser.add_argument("--cue", type=Path, required=True)
    parser.add_argument("--header", type=Path, required=True)
    args = parser.parse_args()

    tracks = [(wav, number) for number, wav in enumerate(
        sorted(args.music_dir.glob("*.wav"), key=lambda item: item.name), start=2
    )]
    if not tracks:
        raise SystemExit(f"no WAV files in {args.music_dir}")
    for wav, _ in tracks:
        convert_wav(wav, Path(f"{args.output}_{stem_macro(wav)}.bin"))
    write_header(args.header, tracks)
    write_cue(args.cue, args.output, tracks)


if __name__ == "__main__":
    main()
